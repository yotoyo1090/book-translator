let langueUI = LANGUE_UI_DEFAUT;
try { langueUI = localStorage.getItem("ui") || LANGUE_UI_DEFAUT; } catch (e) { /* stockage bloqué */ }
if (!I18N[langueUI]) langueUI = LANGUE_UI_DEFAUT;

function t(cle, params = {}) {
  const s = (I18N[langueUI] || {})[cle] ?? I18N.en[cle] ?? I18N.fr[cle] ?? cle;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? params[k] : m));
}

// Nom d'une langue (code ISO) dans la langue de l'interface : « 영어 », « Anglais »…
function nomLangue(code) {
  try {
    const n = new Intl.DisplayNames([langueUI], { type: "language" }).of(code);
    return n ? n.charAt(0).toLocaleUpperCase(langueUI) + n.slice(1) : code;
  } catch (e) { return code; }
}

