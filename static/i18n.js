function tradUnMessage(texte) {
  for (const [re, cle, noms = []] of MESSAGES_SERVEUR) {
    const m = texte.match(re);
    if (!m) continue;
    const params = {};
    noms.forEach((nom, i) => {
      const v = m[i + 1];
      if (nom.startsWith("*")) params[nom.slice(1)] = tradServeur(v);
      else params[nom] = v;
    });
    return t(cle, params);
  }
  return texte;
}

function tradServeur(texte) {
  if (!texte) return "";
  return String(texte).split(" · ").map((s) => tradUnMessage(s.trim())).join(" · ");
}
